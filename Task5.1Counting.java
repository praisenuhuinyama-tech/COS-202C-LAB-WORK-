public class Counting {
    public static void main(String[] args) {
        for (int i = 1; i <= 20; i++) {
            System.out.print(i + " ");
        }
        System.out.println();

        for (int i = 20; i >= 2; i -= 2) {
            System.out.print(i + " ");
        }
        System.out.println();
    }
}